#!/usr/bin/env python3
"""Generates assets/chat_webview/chrome/icons.js from the Material Icons font.

The chat chrome (header, composer, drawer) is drawn inside the chat WebView,
which has no access to Flutter's icon font. Every icon the chrome can show is
baked here as an SVG path, keyed by the Flutter codepoint the Dart side sends.

    python3 -m venv /tmp/ftv && /tmp/ftv/bin/pip install fonttools
    /tmp/ftv/bin/python tools/chrome_icons/generate.py

The icon list is `icons.txt` next to this script; `test/chat_chrome_icons_test.dart`
fails when the Dart side can emit an icon that is missing from it.
"""
import os
import re
import sys

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
FLUTTER = os.environ.get('FLUTTER_ROOT', '/opt/flutter')
ICONS_DART = os.path.join(FLUTTER, 'packages/flutter/lib/src/material/icons.dart')
FONT = os.path.join(FLUTTER, 'bin/cache/artifacts/material_fonts/MaterialIcons-Regular.otf')
OUT = os.path.join(ROOT, 'assets/chat_webview/chrome/icons.js')


def main():
    names = []
    with open(os.path.join(HERE, 'icons.txt')) as f:
        for line in f:
            line = line.split('#', 1)[0].strip()
            if line:
                names.append(line)
    source = open(ICONS_DART).read()
    font = TTFont(FONT)
    upem = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    entries = {}
    for name in sorted(set(names)):
        m = re.search(r'static const IconData ' + re.escape(name) + r'\s*=\s*IconData\(\s*(0x[0-9a-fA-F]+)', source)
        if not m:
            sys.exit('unknown icon: ' + name)
        cp = int(m.group(1), 16)
        glyph = cmap.get(cp)
        if glyph is None:
            sys.exit('no glyph for %s (%s)' % (name, hex(cp)))
        pen = SVGPathPen(glyphs)
        # Font units are y-up with the baseline at the bottom of the em box;
        # flip them into a y-down 0..upem viewBox.
        glyphs[glyph].draw(TransformPen(pen, (1, 0, 0, -1, 0, upem)))
        entries[cp] = (name, pen.getCommands())
    lines = [
        '// Generated by tools/chrome_icons/generate.py — do not edit.',
        '// Material Icons glyphs the chat chrome can draw, keyed by the Flutter',
        '// codepoint (IconData.codePoint). viewBox is 0 0 %d %d.' % (upem, upem),
        'export const ICON_VIEWBOX = \'0 0 %d %d\';' % (upem, upem),
        'export const ICON_PATHS = Object.freeze({',
    ]
    for cp in sorted(entries):
        name, d = entries[cp]
        lines.append('  %d: \'%s\', // %s' % (cp, d, name))
    lines.append('});')
    lines.append('// The same glyphs by Flutter name, for the icons the chrome draws itself.')
    lines.append('export const ICON = Object.freeze({')
    for cp in sorted(entries, key=lambda c: entries[c][0]):
        lines.append('  %s: Object.freeze({ cp: %d }),' % (entries[cp][0], cp))
    lines.append('});')
    with open(OUT, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %d icons to %s' % (len(entries), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    main()
